#!/usr/bin/env python3
"""
Build the Writing section of emilianocar.com.

    pip install markdown
    python3 _tools/build_writing.py                  # published posts only
    python3 _tools/build_writing.py --include-drafts # preview drafts locally (never commit that build)

Reads  : _writing/*.md          (Markdown + a small front-matter block)
Writes : writing/<slug>.html    one page per post (curly quotes applied by _tools/typeset.py)
         index.html             the list inside the Writing window (only between the writing:* markers)
         feed.xml               RSS feed (for feed readers)
         subscribe.html         the page visitors see when they click "RSS feed"
         sitemap.xml            (only the /writing/ lines are touched)

Front matter (top of each .md file, between two '---' lines):

    title:    My post title            (required)
    date:     2026-10-11               (required, YYYY-MM-DD)
    category: tech                     (required: tech or personal)
    summary:  One or two sentences.    (recommended; used in the list, search and link previews)
    tags:     security, notes          (optional, comma separated; searchable, used in the feed)
    draft:    true                     (optional; drafts are skipped unless --include-drafts)
    updated:  2026-11-02               (optional)
    slug:     custom-url-name          (optional; defaults to the file name)
    image:    /images/writing/x.png    (optional; link-preview image)
"""
import argparse, datetime as dt, email.utils, html, re, sys
from pathlib import Path

try:
    import markdown
except ImportError:
    sys.exit("Missing dependency. Run:  pip install markdown")

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "_writing"
OUT = ROOT / "writing"
SITE = "https://emilianocar.com"
AUTHOR = "Emiliano Carrizosa"
MARKER = "<!-- generated by _tools/build_writing.py: edit _writing/*.md instead -->"
DEFAULT_IMAGE = SITE + "/og-image.png"
CAPTION = "Zellige tile · Morocco"
CATEGORIES = {"tech": "Tech", "personal": "Personal"}

esc = html.escape


def parse(path: Path):
    text = path.read_text(encoding="utf-8").lstrip("﻿")
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", text, re.S)
    if not m:
        sys.exit(f"{path.name}: missing front matter (--- block at top of file)")
    meta = {}
    for line in m.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        k, _, v = line.partition(":")
        v = v.strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
            v = v[1:-1]
        meta[k.strip().lower()] = v
    for req in ("title", "date"):
        if not meta.get(req):
            sys.exit(f"{path.name}: front matter needs '{req}'")
    try:
        date = dt.date.fromisoformat(meta["date"])
    except ValueError:
        sys.exit(f"{path.name}: date must look like 2026-10-11")
    updated = None
    if meta.get("updated"):
        try:
            updated = dt.date.fromisoformat(meta["updated"])
        except ValueError:
            sys.exit(f"{path.name}: 'updated' must look like 2026-10-11")
    cat = (meta.get("category") or "tech").strip().lower()
    if cat not in CATEGORIES:
        sys.exit(f"{path.name}: category must be one of: {', '.join(CATEGORIES)} (got '{cat}')")
    body = m.group(2).strip()
    slug = re.sub(r"[^a-z0-9-]+", "-", (meta.get("slug") or path.stem).lower()).strip("-")
    tags = [re.sub(r"[^a-z0-9-]+", "-", t.strip().lower()).strip("-")
            for t in meta.get("tags", "").split(",") if t.strip()]
    # editorial extras: {{pull: a line to set large}} on its own line, {{note: a margin note}} inline
    body = re.sub(r"^\{\{pull:\s*(.+?)\}\}\s*$", lambda m: '\n<aside class="pull" role="note">' + m.group(1) + '</aside>\n', body, flags=re.M)
    body = re.sub(r"\{\{note:\s*(.+?)\}\}", lambda m: '<span class="note" role="note">' + m.group(1) + '</span>', body)
    md = markdown.Markdown(extensions=["extra", "sane_lists", "smarty"])
    content = md.convert(body)
    # an image with a title becomes a numbered figure: ![alt](/path.png "Caption")
    content = re.sub(r'<p><img ([^>]*?)\s*title="([^"]*)"([^>]*?)\s*/?></p>',
                     lambda m: f'<figure><img {m.group(1)} {m.group(3)}><figcaption>{m.group(2)}</figcaption></figure>'.replace("  ", " "), content)
    plain = re.sub(r"<[^>]+>", " ", content)
    plain = html.unescape(re.sub(r"\s+", " ", plain)).strip()
    words = len(plain.split())
    summary = meta.get("summary") or (plain[:157].rsplit(" ", 1)[0] + "…" if len(plain) > 160 else plain)
    return dict(title=meta["title"], date=date, updated=updated, slug=slug, tags=tags, cat=cat,
                draft=meta.get("draft", "").lower() in ("true", "yes", "1"),
                summary=summary, content=content, minutes=max(1, round(words / 200)),
                image=meta.get("image", ""), file=path.name)


def fmt_date(d):
    return f"{d.strftime('%B')} {d.day}, {d.year}"


