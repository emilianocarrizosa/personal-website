# ---------------------------------------------------------------- feed + sitemap
def absolutize(htmltext):
    return re.sub(r'(src|href)="/(?!/)', rf'\1="{SITE}/', htmltext)


def feed(posts):
    now = email.utils.format_datetime(dt.datetime.now(dt.timezone.utc))
    items = []
    for p in posts[:20]:
        d = email.utils.format_datetime(dt.datetime.combine(p["date"], dt.time(12), tzinfo=dt.timezone.utc))
        link = f"{SITE}/writing/{p['slug']}.html"
        body = absolutize(p["content"]).replace("]]>", "]]&gt;")
        cats = f"<category>{CATEGORIES[p['cat']]}</category>" + "".join(f"<category>{esc(t)}</category>" for t in p["tags"])
        items.append(f"""    <item>
      <title>{esc(p['title'])}</title>
      <link>{link}</link>
      <guid isPermaLink="true">{link}</guid>
      <pubDate>{d}</pubDate>
      <description>{esc(p['summary'])}</description>
      {cats}
      <content:encoded><![CDATA[{body}]]></content:encoded>
    </item>""")
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:content="http://purl.org/rss/1.0/modules/content/">
  <channel>
    <title>{AUTHOR} — Writing</title>
    <link>{SITE}/#writing</link>
    <atom:link href="{SITE}/feed.xml" rel="self" type="application/rss+xml"/>
    <description>Articles and blog posts by {AUTHOR}.</description>
    <language>en-us</language>
    <lastBuildDate>{now}</lastBuildDate>
{chr(10).join(items)}
  </channel>
</rss>
"""


def update_sitemap(posts):
    sm = ROOT / "sitemap.xml"
    lines = [l for l in sm.read_text(encoding="utf-8").splitlines() if "/writing/" not in l]
    add = [f"  <url><loc>{SITE}/writing/{p['slug']}.html</loc><lastmod>{(p['updated'] or p['date']).isoformat()}</lastmod></url>"
           for p in posts]
    i = next(n for n, l in enumerate(lines) if "</urlset>" in l)
    sm.write_text("\n".join(lines[:i] + add + lines[i:]) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--include-drafts", action="store_true", help="also build posts marked draft: true (local preview only)")
    args = ap.parse_args()

    SRC.mkdir(exist_ok=True)
    posts = [parse(f) for f in sorted(SRC.glob("*.md")) if not f.name.startswith(("_", "."))]
    slugs = [p["slug"] for p in posts]
    dupes = {s for s in slugs if slugs.count(s) > 1}
    if dupes:
        sys.exit(f"Duplicate slug(s): {', '.join(sorted(dupes))}")
    shown = [p for p in posts if args.include_drafts or not p["draft"]]
    shown.sort(key=lambda p: (p["date"], p["slug"]), reverse=True)

    OUT.mkdir(exist_ok=True)
    for f in OUT.glob("*.html"):                       # prune only files this script made
        if MARKER in f.read_text(encoding="utf-8", errors="ignore")[:400]:
            f.unlink()
    for i, p in enumerate(shown):                      # shown is newest first
        newer = shown[i - 1] if i > 0 else None
        older = shown[i + 1] if i + 1 < len(shown) else None
        (OUT / f"{p['slug']}.html").write_text(post_page(p, newer, older), encoding="utf-8")
    inject_index(shown)

    public = [p for p in shown if not p["draft"]]
    (ROOT / "feed.xml").write_text(feed(public), encoding="utf-8")
    (ROOT / "subscribe.html").write_text(subscribe_page(public), encoding="utf-8")
    update_sitemap(public)

    from typeset import typeset_file                    # curly quotes in the finished pages
    for f in [ROOT / "index.html", ROOT / "subscribe.html", *OUT.glob("*.html")]:
        typeset_file(f)

    if not any(OUT.iterdir()):
        OUT.rmdir()
    drafts = len([p for p in shown if p["draft"]])
    print(f"Built {len(shown)} post(s) ({drafts} draft) -> index.html (Writing window), feed.xml, subscribe.html, sitemap.xml")
    for p in shown:
        print(f"  {'[draft] ' if p['draft'] else ''}{p['date']}  [{p['cat']}]  /writing/{p['slug']}.html  ({p['minutes']} min)")


if __name__ == "__main__":
    main()
