#!/usr/bin/env python3
"""
Build the Writing section of emilianocar.com.

    pip install markdown
    python3 _tools/build_writing.py                  # published posts only
    python3 _tools/build_writing.py --include-drafts # preview drafts locally

Reads  : _writing/*.md          (Markdown + a small front-matter block)
Writes : writing/<slug>.html    one page per post
         writing.html           the index
         feed.xml               RSS feed
         sitemap.xml            (only the /writing* lines are touched)

Front matter (top of each .md file, between two '---' lines):

    title:   My post title            (required)
    date:    2026-10-11               (required, YYYY-MM-DD)
    summary: One or two sentences.    (recommended; used on cards, search and link previews)
    tags:    security, notes          (optional, comma separated)
    draft:   true                     (optional; drafts are skipped unless --include-drafts)
    updated: 2026-11-02               (optional)
    slug:    custom-url-name          (optional; defaults to the file name)
    image:   /images/writing/x.png    (optional; link-preview image)
"""
import argparse, datetime as dt, email.utils, html, re, sys
from pathlib import Path

try:
    import markdown
except ImportError:
    sys.exit("Missing dependency. Run:  pip install markdown")

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "_writing"
OUT = ROOT / "writing"
SITE = "https://emilianocar.com"
AUTHOR = "Emiliano Carrizosa"
MARKER = "<!-- generated by _tools/build_writing.py: edit _writing/*.md instead -->"
DEFAULT_IMAGE = SITE + "/og-image.png"

NAV = [("Work", "work"), ("About", "about"), ("Experience", "experience"),
       ("Services", "services"), ("Skills", "skills"), ("Writing", "writing")]

esc = html.escape


def parse(path: Path):
    text = path.read_text(encoding="utf-8").lstrip("﻿")
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", text, re.S)
    if not m:
        sys.exit(f"{path.name}: missing front matter (--- block at top of file)")
    meta = {}
    for line in m.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        k, _, v = line.partition(":")
        v = v.strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
            v = v[1:-1]
        meta[k.strip().lower()] = v
    for req in ("title", "date"):
        if not meta.get(req):
            sys.exit(f"{path.name}: front matter needs '{req}'")
    try:
        date = dt.date.fromisoformat(meta["date"])
    except ValueError:
        sys.exit(f"{path.name}: date must look like 2026-10-11")
    updated = None
    if meta.get("updated"):
        try:
            updated = dt.date.fromisoformat(meta["updated"])
        except ValueError:
            sys.exit(f"{path.name}: 'updated' must look like 2026-10-11")
    body = m.group(2).strip()
    slug = re.sub(r"[^a-z0-9-]+", "-", (meta.get("slug") or path.stem).lower()).strip("-")
    tags = [re.sub(r"[^a-z0-9-]+", "-", t.strip().lower()).strip("-")
            for t in meta.get("tags", "").split(",") if t.strip()]
    md = markdown.Markdown(extensions=["extra", "sane_lists", "smarty"])
    content = md.convert(body)
    plain = re.sub(r"<[^>]+>", " ", content)
    plain = html.unescape(re.sub(r"\s+", " ", plain)).strip()
    words = len(plain.split())
    summary = meta.get("summary") or (plain[:157].rsplit(" ", 1)[0] + "…" if len(plain) > 160 else plain)
    return dict(title=meta["title"], date=date, updated=updated, slug=slug, tags=tags,
                draft=meta.get("draft", "").lower() in ("true", "yes", "1"),
                summary=summary, content=content, minutes=max(1, round(words / 200)),
                image=meta.get("image", ""), file=path.name)


def fmt_date(d):
    return f"{d.strftime('%B')} {d.day}, {d.year}"


def head(title, desc, canonical, css_prefix, kind="website", noindex=False, image=DEFAULT_IMAGE, extra=""):
    t, d = esc(title, quote=True), esc(desc, quote=True)
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
    {MARKER}
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{esc(title)}</title>
    <meta name="description" content="{d}">
    <link rel="canonical" href="{canonical}">
    {'<meta name="robots" content="noindex">' if noindex else ''}
    <meta name="color-scheme" content="dark light">
    <meta name="theme-color" content="#161616" media="(prefers-color-scheme: dark)">
    <meta name="theme-color" content="#F3F3F3" media="(prefers-color-scheme: light)">
    <meta property="og:type" content="{kind}">
    <meta property="og:site_name" content="{AUTHOR}">
    <meta property="og:title" content="{t}">
    <meta property="og:description" content="{d}">
    <meta property="og:url" content="{canonical}">
    <meta property="og:image" content="{esc(image, quote=True)}">
    <meta name="twitter:card" content="summary_large_image">
    <meta name="twitter:title" content="{t}">
    <meta name="twitter:description" content="{d}">
    <meta name="twitter:image" content="{esc(image, quote=True)}">
    <link rel="alternate" type="application/rss+xml" title="{AUTHOR} — Writing" href="/feed.xml">
    <link rel="icon" href="/favicon.svg" type="image/svg+xml">
    <link rel="icon" href="/favicon.png" sizes="32x32" type="image/png">
    <link rel="apple-touch-icon" href="/apple-touch-icon.png">
    <link rel="preconnect" href="https://fonts.googleapis.com">
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
    <link href="https://fonts.googleapis.com/css2?family=DM+Sans:wght@400;500;600&display=swap" rel="stylesheet">
    <link rel="stylesheet" href="{css_prefix}css/bento.css">
    <link rel="stylesheet" href="{css_prefix}css/project.css">
    <link rel="stylesheet" href="{css_prefix}css/writing.css">{extra}
</head>
"""


def topbar(prefix):
    cur = ' aria-current="page"'
    links = "\n".join(
        f'                <a href="{prefix}{slug}.html"{cur if slug == "writing" else ""}>{label}</a>'
        for label, slug in NAV)
    home = "/" if prefix else "index.html"
    return f"""    <a class="skip" href="#main">Skip to content</a>

    <header class="top">
        <div class="top-in">
            <a class="back" href="{home}"><span aria-hidden="true">←</span> Home</a>
            <nav aria-label="Primary">
{links}
            </nav>
        </div>
    </header>
"""


FOOT = """    <footer class="foot">
        <span>© 2026 Emiliano Carrizosa · New York, NY</span>
        <a href="{link}">{label}</a>
    </footer>
</body>
</html>
"""


def post_page(p):
    url = f"{SITE}/writing/{p['slug']}.html"
    img = p["image"]
    if img.startswith("/"):
        img = SITE + img
    tags = "".join(f'\n                <span class="tag">#{esc(t)}</span>' for t in p["tags"])
    meta = f"{fmt_date(p['date'])} · {p['minutes']} min read"
    if p["updated"] and p["updated"] > p["date"]:
        meta += f" · Updated {fmt_date(p['updated'])}"
    if p["draft"]:
        meta = "DRAFT · " + meta
    return (head(f"{p['title']} — {AUTHOR}", p["summary"], url, "/", kind="article",
                 noindex=p["draft"], image=img or DEFAULT_IMAGE)
            + f"""<body>
{topbar('/')}
    <main id="main" class="page proj article">
        <header class="project-header">
            <a href="/writing.html" class="back-link">← All writing</a>
            <h1 class="project-title">{esc(p['title'])}</h1>
            <p class="project-subtitle">{esc(p['summary'])}</p>
            <p class="project-meta">{esc(meta)}</p>
            {f'<div>{tags}\n            </div>' if p['tags'] else ''}
        </header>

        <article class="content">
{p['content']}
        </article>

        <div class="article-end">
            <p class="t-text">Thoughts or corrections? <a href="mailto:emiliano.carrizosa@proton.me">Send me an email</a>.</p>
            <a class="btn" href="/writing.html"><span aria-hidden="true">←</span> All writing</a>
        </div>
    </main>

"""
            + FOOT.format(link="/writing.html", label="← All writing"))


def index_page(posts, drafts_shown):
    url = f"{SITE}/writing.html"
    desc = "Articles and blog posts by Emiliano Carrizosa on IT, security, and the things he's learning."
    if posts:
        tiles = []
        for i, p in enumerate(posts):
            span = "c12" if i == 0 and len(posts) > 1 else "c6"
            tags = ("<ul class=\"pills\" aria-label=\"Tags\">" +
                    "".join(f"<li>{esc(t)}</li>" for t in p["tags"][:4]) + "</ul>") if p["tags"] else ""
            label = f"Draft · {fmt_date(p['date'])}" if p["draft"] else fmt_date(p["date"])
            tiles.append(f"""            <article class="tile tile--link post-tile {span}">
                <p class="post-date">{label} · {p['minutes']} min read</p>
                <h2 class="t-title"><a class="stretched" href="writing/{p['slug']}.html">{esc(p['title'])}</a></h2>
                <p class="t-text">{esc(p['summary'])}</p>
                {tags}
                <span class="t-arrow" aria-hidden="true">↗</span>
            </article>""")
        grid = "\n\n".join(tiles)
    else:
        grid = """            <div class="tile c12" style="min-height:220px; justify-content:center">
                <span class="label">Nothing here yet</span>
                <h2 class="t-title t-title--lg" style="padding-right:0">First article coming soon</h2>
                <p class="t-text">I'm starting to write about IT, security and the things I'm learning along the way. Check back soon, or follow along with the feed.</p>
                <div class="t-foot"><a class="btn" href="feed.xml">RSS feed <span aria-hidden="true">→</span></a></div>
            </div>"""
    return (head(f"Writing — {AUTHOR}", desc, url, "")
            + f"""<body>
{topbar('')}
    <main id="main" class="page">
        <div class="page-head">
            <h1>Writing</h1>
            <p class="lead">Articles and blog posts on IT, security and whatever I'm learning. A creative hobby, written in my own time.</p>
        </div>

        <div class="grid">
{grid}
        </div>
    </main>

"""
            + FOOT.format(link="index.html", label="← Home"))


def absolutize(htmltext):
    return re.sub(r'(src|href)="/(?!/)', rf'\1="{SITE}/', htmltext)


def feed(posts):
    now = email.utils.format_datetime(dt.datetime.now(dt.timezone.utc))
    items = []
    for p in posts[:20]:
        d = email.utils.format_datetime(dt.datetime.combine(p["date"], dt.time(12), tzinfo=dt.timezone.utc))
        link = f"{SITE}/writing/{p['slug']}.html"
        body = absolutize(p["content"]).replace("]]>", "]]&gt;")
        cats = "".join(f"<category>{esc(t)}</category>" for t in p["tags"])
        items.append(f"""    <item>
      <title>{esc(p['title'])}</title>
      <link>{link}</link>
      <guid isPermaLink="true">{link}</guid>
      <pubDate>{d}</pubDate>
      <description>{esc(p['summary'])}</description>
      {cats}
      <content:encoded><![CDATA[{body}]]></content:encoded>
    </item>""")
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:content="http://purl.org/rss/1.0/modules/content/">
  <channel>
    <title>{AUTHOR} — Writing</title>
    <link>{SITE}/writing.html</link>
    <atom:link href="{SITE}/feed.xml" rel="self" type="application/rss+xml"/>
    <description>Articles and blog posts by {AUTHOR}.</description>
    <language>en-us</language>
    <lastBuildDate>{now}</lastBuildDate>
{chr(10).join(items)}
  </channel>
</rss>
"""


def update_sitemap(posts):
    sm = ROOT / "sitemap.xml"
    lines = [l for l in sm.read_text(encoding="utf-8").splitlines() if "/writing" not in l]
    newest = max([p["date"] for p in posts], default=None)
    add = [f"  <url><loc>{SITE}/writing.html</loc>"
           + (f"<lastmod>{newest.isoformat()}</lastmod>" if newest else "") + "</url>"]
    add += [f"  <url><loc>{SITE}/writing/{p['slug']}.html</loc><lastmod>{(p['updated'] or p['date']).isoformat()}</lastmod></url>"
            for p in posts]
    i = next(n for n, l in enumerate(lines) if "</urlset>" in l)
    sm.write_text("\n".join(lines[:i] + add + lines[i:]) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--include-drafts", action="store_true", help="also build posts marked draft: true (local preview only)")
    args = ap.parse_args()

    SRC.mkdir(exist_ok=True)
    posts = [parse(f) for f in sorted(SRC.glob("*.md")) if not f.name.startswith(("_", "."))]
    slugs = [p["slug"] for p in posts]
    dupes = {s for s in slugs if slugs.count(s) > 1}
    if dupes:
        sys.exit(f"Duplicate slug(s): {', '.join(sorted(dupes))}")
    shown = [p for p in posts if args.include_drafts or not p["draft"]]
    shown.sort(key=lambda p: (p["date"], p["slug"]), reverse=True)

    OUT.mkdir(exist_ok=True)
    for f in OUT.glob("*.html"):                       # prune only files this script made
        if MARKER in f.read_text(encoding="utf-8", errors="ignore")[:400]:
            f.unlink()
    for p in shown:
        (OUT / f"{p['slug']}.html").write_text(post_page(p), encoding="utf-8")
    (ROOT / "writing.html").write_text(index_page(shown, args.include_drafts), encoding="utf-8")

    public = [p for p in shown if not p["draft"]]
    (ROOT / "feed.xml").write_text(feed(public), encoding="utf-8")
    update_sitemap(public)

    if not any(OUT.iterdir()):
        OUT.rmdir()
    drafts = len([p for p in shown if p["draft"]])
    print(f"Built {len(shown)} post(s) ({drafts} draft) -> writing.html, feed.xml, sitemap.xml")
    for p in shown:
        print(f"  {'[draft] ' if p['draft'] else ''}{p['date']}  /writing/{p['slug']}.html  ({p['minutes']} min)")


if __name__ == "__main__":
    main()
